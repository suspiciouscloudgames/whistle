export function userErrorMessage(error: unknown, fallback: string) {
  return error instanceof Error && Object.hasOwn(english, error.message) ? error.message : fallback;
}

const LanguageContext = createContext({
  language: "ko" as Language,
  setLanguage: (_language: Language) => {},
  t: (text: string): string => text,
});
const STORAGE = "whistle.language";
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>("ko");
  useEffect(() => {
    try {
      if (localStorage.getItem(STORAGE) === "en") updateLanguage("en");
    } catch {

    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const setLanguage = useCallback((next: Language) => {
    updateLanguage(next);
    try {
      localStorage.setItem(STORAGE, next);
    } catch {

    }
  }, []);
  const t = useCallback(
    (text: string) => (language === "en" ? (english[text] ?? text) : text),
    [language],
  );
  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}
export const useLanguage = () => useContext(LanguageContext);
export function SceneLoading() {
  const { t } = useLanguage();
  return <div className="scene scene-loading" aria-label={t("불러오는 중")} />;
}
